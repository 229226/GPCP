import nr_pbch as P

# --- triangular_deinterleave inverse permutation (output k <- input idx) ---
def tri_perm(E=720):
    t=P._tri_t(E); cells=P._tri_cells(t,E)
    cset=set(cells); colidx={}; idx=0
    for j in range(t):
        for i in range(t):
            if (i,j) in cset:
                colidx[(i,j)]=idx; idx+=1
    return [colidx[cells[k]] for k in range(E)]

# --- subblock_deinterleave inverse permutation (output k <- input idx) ---
def sb_perm(N=512):
    c=32; r=N//c
    pidx={p:i for i,p in enumerate(P.SUBBLK_PERM)}
    out=[]
    for k in range(N):
        ri=k//c; ci=k%c
        out.append(pidx[ci]*r+ri)
    return out

tp=tri_perm(720); sb=sb_perm(512)

# verify against rate_recover_pbch
import random
random.seed(11)
for _ in range(20):
    e=[random.randint(0,1) for _ in range(720)]
    ref=P.rate_recover_pbch(e,512)   # list of 0/1 (polar bits) as LLR-like? returns 0/1 bits
    # build LLRs from e (sign): +1 for 0, -1 for 1
    ellr=[ (1 if b==0 else -1) for b in e ]
    z=[ ellr[tp[m]] for m in range(720) ]
    pre=[0]*512
    for k in range(720): pre[k%512]+=z[k]
    got=[ 0 if pre[sb[i]]>=0 else 1 for i in range(512) ]
    # ref is 0/1 bits (the recovered codeword); compare
    if got!=ref:
        print("MISMATCH"); break
else:
    print("LUT round-trip OK (20 random vectors)")

