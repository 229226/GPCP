#!/usr/bin/env python3
"""Generate the inverse PDCCH rate-matching LUTs (E=432, N=512).

Same composition as gen_luts.py but with the PDCCH aggregation-level-4 length:

    zrm[m]  = e432[tri_perm[m]]      (inverse triangular de-interleave)
    pre[k] += zrm[k]                 (E < N, so no circular wrap / repetition)
    llr[i]  = pre[sb_perm[i]]        (inverse sub-block de-interleave)

pre[432..511] stays 0 = punctured polar bits, exactly what
nr_pbch.rate_recover_pbch() produces.
"""
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import nr_pbch as P
import gen_luts as G

E = 432
N = 512


def recover(e, tp, sb):
    zrm = [e[tp[m]] for m in range(E)]
    pre = [0] * N
    for k in range(E):
        pre[k % N] += zrm[k]
    return [pre[sb[i]] for i in range(N)]


def emit(f, name, arr, per=12):
    f.write("static const int %s[%d] = {\n" % (name, len(arr)))
    for i in range(0, len(arr), per):
        f.write("  " + ",".join(str(v) for v in arr[i:i + per]) + ",\n")
    f.write("};\n\n")


def main():
    tp, sb = G.tri_perm(E), G.sb_perm(N)
    rnd = random.Random(3)
    for _ in range(50):
        e = [rnd.choice((1, -1, 3, -2)) for _ in range(E)]
        if recover(e, tp, sb) != P.rate_recover_pbch(e, N):
            print("[FAIL] LUT composition does not match rate_recover_pbch")
            return 1
    path = sys.argv[1] if len(sys.argv) > 1 else "pdcch_luts.h"
    with open(path, "w") as f:
        f.write("/* Auto-generated by gen_pdcch_luts.py -- inverse PDCCH rate-matching LUTs. */\n")
        f.write("#ifndef PDCCH_LUTS_H\n#define PDCCH_LUTS_H\n\n")
        f.write("#define RM_LEN 432\n#define POLAR_N 512\n\n")
        emit(f, "tri_perm", tp)
        emit(f, "sb_perm", sb)
        f.write("#endif\n")
    print("wrote %s (E=%d, N=%d, self-test OK)" % (path, E, N))
    return 0


if __name__ == "__main__":
    sys.exit(main())
