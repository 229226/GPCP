# --- end bootstrap ---
"""Generate tools/ssb_fid_luts.h (inverse PBCH rate-matching permutation LUTs).

The C benchmark (sw/soc/bench/ssb_fid_bm.c) recovers the 512 polar LLRs from the
720 rate-matched ones with two permutations plus the circular-buffer sum:

    zrm[m]  = e720[tri_perm[m]]          (inverse triangular de-interleave)
    pre[k] += zrm[k % 512]               (circular buffer, LLR accumulation)
    llr[i]  = pre[sb_perm[i]]            (inverse sub-block de-interleave)

This script emits both tables and checks that composition against
nr_pbch.rate_recover_pbch() -- importing the module has no side effects.
"""
import nr_pbch as P

E = 720
N = 512


# --- triangular_deinterleave permutation (output m <- input idx) -------------
def tri_perm(e_len=E):
    t = P._tri_t(e_len)
    cells = P._tri_cells(t, e_len)
    cset = set(cells)
    colidx = {}
    idx = 0
    for j in range(t):
        for i in range(t):
            if (i, j) in cset:
                colidx[(i, j)] = idx
                idx += 1
    return [colidx[cells[k]] for k in range(e_len)]


# --- subblock_deinterleave permutation (output i <- input idx) ---------------
def sb_perm(n=N):
    c = 32
    r = n // c
    pidx = {p: i for i, p in enumerate(P.SUBBLK_PERM)}
    out = []
    for k in range(n):
        ri = k // c
        ci = k % c
        out.append(pidx[ci] * r + ri)
    return out


def recover(e720, tp, sb):
    """The exact composition the C code performs (LLRs, additive)."""
    zrm = [e720[tp[m]] for m in range(E)]
    pre = [0] * N
    for k in range(E):
        pre[k % N] += zrm[k]
    return [pre[sb[i]] for i in range(N)]


def self_test(tp, sb, vectors=50):
    import random
    rnd = random.Random(11)
    for _ in range(vectors):
        e = [rnd.choice([1, -1]) for _ in range(E)]
        if recover(e, tp, sb) != P.rate_recover_pbch(e, N):
            return False
    return True


def write_header(path, tp, sb):
    with open(path, "w") as f:
        f.write("/* Auto-generated by gen_luts.py -- inverse PBCH rate-matching LUTs (P1). */\n")
        f.write("#ifndef SSB_FID_LUTS_H\n#define SSB_FID_LUTS_H\n\n")
        f.write("#define RM_LEN 720\n#define POLAR_N 512\n\n")
        f.write("static const int tri_perm[720] = {\n")
        for i in range(0, E, 12):
            f.write("  " + ",".join(str(x) for x in tp[i:i + 12]) + ",\n")
        f.write("};\n\n")
        f.write("static const int sb_perm[512] = {\n")
        for i in range(0, N, 12):
            f.write("  " + ",".join(str(x) for x in sb[i:i + 12]) + ",\n")
        f.write("};\n\n")
        f.write("#endif /* SSB_FID_LUTS_H */\n")


if __name__ == "__main__":
    import os
    tp = tri_perm()
    sb = sb_perm()
    assert self_test(tp, sb), "LUT composition disagrees with nr_pbch.rate_recover_pbch"
    print("LUT round-trip OK (%d random vectors)" % 50)
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ssb_fid_luts.h")
    write_header(out, tp, sb)
    print("wrote", out, "(tri_perm 720, sb_perm 512)")
