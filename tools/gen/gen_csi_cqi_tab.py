#!/usr/bin/env python3
# --- tools path bootstrap (subdirs import root modules) ---
import os as _os, sys as _sys
_T = _os.path.dirname(_os.path.abspath(__file__))
_TOOLS = _T if _os.path.basename(_T) == "tools" else _os.path.dirname(_T)
for _p in (_TOOLS, _os.path.join(_TOOLS, "models"), _os.path.join(_TOOLS, "checks"),
           _os.path.join(_os.path.dirname(_TOOLS), "cgra", "tools")):
    if _p not in _sys.path:
        _sys.path.insert(0, _p)
_ROOT = _os.path.dirname(_TOOLS)
# --- end bootstrap ---
"""Generate sw/soc/gen/csi_cqi_tab.h: linear (Q8) SNR thresholds per CQI.

The thresholds are exactly the ones nr_la.cqi_from_sinr() uses
(required_snr_db + SPREAD_DB * Q^-1(0.1)), converted to a linear Q8 ratio so
the bare-metal CQI selector needs no logarithm.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import nr_csi as C

thr = C.cqi_thresholds()
lines = [
    "/* Generated by tools/gen/gen_csi_cqi_tab.py -- do not edit.",
    "   Linear Q8 SNR threshold for every CQI (index 0 unused).",
    "   cqi = max c such that snr_q8 >= csi_cqi_thr_q8[c]. */",
    "#ifndef CSI_CQI_TAB_H",
    "#define CSI_CQI_TAB_H",
    "",
    "static const int32_t csi_cqi_thr_q8[16] = {",
]
lines.append("    " + ", ".join("%9d" % v for v in thr) + ",")
lines += ["};", "", "#endif /* CSI_CQI_TAB_H */", ""]
open("sw/soc/gen/csi_cqi_tab.h", "w").write("\n".join(lines))
print("wrote sw/soc/gen/csi_cqi_tab.h: %s" % thr)
