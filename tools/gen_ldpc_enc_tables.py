#!/usr/bin/env python3
"""Emit sw/include/ldpc_enc_tables.h: the four (BG, i_LS) tables B1 needs.

Unlike gen_ldpc_header.py (one header per graph, symbols shared between lifting
sets), this emits all four variants into one header with prefixed symbols, so a
single benchmark can select (BG, Zc) at run time.  It also carries the three
double-diagonal core parameters A_V / B_V / RB that the encoder needs.

    BG1/ils0 (Zc=64)  BG1/ils2 (Zc=20)  BG2/ils0 (Zc=64)  BG2/ils2 (Zc=20)
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ldpc_nr as NR

COMBOS = ((1, 0), (1, 2), (2, 0), (2, 2))


def emit(out):
    L = ["/* generated by tools/gen_ldpc_enc_tables.py, do not edit.",
         " * 38.212 5.3.2 base graphs for the CVA6 LDPC encoder (B1).",
         " * Symbols carry a bg/ils prefix so all four variants coexist. */",
         "#ifndef LDPC_ENC_TABLES_H",
         "#define LDPC_ENC_TABLES_H",
         "",
         "typedef struct {",
         "    unsigned short rows, cols, kb, maxd;",
         "    const unsigned char *deg;",
         "    const unsigned char *col;",
         "    const unsigned short *sh;",
         "    unsigned short a_v, b_v;",
         "    unsigned char rb;",
         "} ldpc_bg_t;",
         ""]
    for bg, ils in COMBOS:
        rows, cols, kb, _ = NR.DIMS[bg]
        t = NR.load_table(bg, ils)
        deg = [sum(1 for v in t[r] if v >= 0) for r in range(rows)]
        maxd = max(deg) + (max(deg) & 1)
        col = [[0] * maxd for _ in range(rows)]
        sh = [[0] * maxd for _ in range(rows)]
        for r in range(rows):
            k = 0
            for c in range(cols):
                if t[r][c] >= 0:
                    col[r][k] = c
                    sh[r][k] = t[r][c]
                    k += 1
        core = [[t[r][kb + c] for c in range(4)] for r in range(4)]
        rb = next(r for r in (1, 2)
                  if core[r][0] >= 0 and sum(1 for v in core[r] if v >= 0) >= 3)
        a_v, b_v = core[0][0], core[rb][0]
        S = "e_bg%d_ils%d" % (bg, ils)
        L.append("/* BG%d i_LS=%d: %d rows x %d cols, Kb=%d, maxd=%d, "
                 "A_V=%d B_V=%d RB=%d */" % (bg, ils, rows, cols, kb, maxd,
                                              a_v, b_v, rb))
        L.append("static const unsigned char %s_deg[%d] = {" % (S, rows))
        for i in range(0, rows, 16):
            L.append("    " + ", ".join(str(d) for d in deg[i:i + 16]) + ",")
        L.append("};")
        L.append("static const unsigned char %s_col[%d][%d] = {" % (S, rows, maxd))
        for r in range(rows):
            L.append("    {" + ", ".join(str(v) for v in col[r]) + "},")
        L.append("};")
        L.append("static const unsigned short %s_sh[%d][%d] = {" % (S, rows, maxd))
        for r in range(rows):
            L.append("    {" + ", ".join(str(v) for v in sh[r]) + "},")
        L.append("};")
        L.append("static const ldpc_bg_t LDPC_BG%d_ILS%d = "
                 "{ %d, %d, %d, %d, %s_deg, &%s_col[0][0], &%s_sh[0][0], "
                 "%d, %d, %d };"
                 % (bg, ils, rows, cols, kb, maxd, S, S, S, a_v, b_v, rb))
        L.append("")
    L.append("#endif /* LDPC_ENC_TABLES_H */")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print("wrote %s: %d variants" % (out, len(COMBOS)))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "sw", "include", "ldpc_enc_tables.h"))
    raise SystemExit(emit(ap.parse_args().out))
