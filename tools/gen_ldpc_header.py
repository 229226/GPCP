#!/usr/bin/env python3
"""Emit a C header with the 38.212 base graph in the form the SoC benches want.

    python3 tools/gen_ldpc_header.py --bg 2 --ils 2 --out sw/include/ldpc_bg2.h
    python3 tools/gen_ldpc_header.py --bg 1 --ils 0 --out sw/include/ldpc_bg1.h

The header carries raw V coefficients (the benches reduce them mod Zc at use
time), the degree of every check node, and the variable block of every edge.

MAXD is the padded row width: the real maximum row degree rounded up to an even
number, because the CN microcode consumes edges in pairs.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ldpc_nr as NR


def emit(bg, ils, out):
    rows, cols, kb, _name = NR.DIMS[bg]
    t = NR.load_table(bg, ils)
    deg = [sum(1 for v in t[r] if v >= 0) for r in range(rows)]
    maxd = max(deg)
    if maxd % 2:
        maxd += 1
    col = [[0] * maxd for _ in range(rows)]
    sh = [[0] * maxd for _ in range(rows)]
    for r in range(rows):
        k = 0
        for c in range(cols):
            if t[r][c] >= 0:
                col[r][k] = c
                sh[r][k] = t[r][c]
                k += 1
    top = max(max(sh[r][k] for k in range(deg[r])) for r in range(rows))
    ctype = "unsigned short" if top > 255 else "unsigned char"
    sym = "bg%d" % bg
    guard = "LDPC_BG%d_ILS%d_H" % (bg, ils)

    lines = []
    lines.append("/* generated by tools/gen_ldpc_header.py --bg %d --ils %d "
                 "(38.212 Table 5.3.2-%d, i_LS = %d)" % (bg, ils, bg + 1, ils))
    lines.append(" * %d rows x %d columns, Kb = %d, max row degree %d (padded to %d). */"
                 % (rows, cols, kb, max(deg), maxd))
    lines.append("#ifndef %s" % guard)
    lines.append("#define %s" % guard)
    lines.append("")
    lines.append("#define BG%d_ROWS %d" % (bg, rows))
    lines.append("#define BG%d_COLS %d" % (bg, cols))
    lines.append("#define BG%d_KB   %d" % (bg, kb))
    lines.append("#define BG%d_MAXD %d" % (bg, maxd))
    lines.append("")
    lines.append("static const unsigned char %s_deg[BG%d_ROWS] = {" % (sym, bg))
    for i in range(0, rows, 16):
        lines.append("    " + ", ".join(str(d) for d in deg[i:i + 16]) + ",")
    lines.append("};")
    lines.append("")
    lines.append("/* %s_col[r][k]: variable block of edge k; %s_sh[r][k]: its lift shift */"
                 % (sym, sym))
    lines.append("static const unsigned char %s_col[BG%d_ROWS][BG%d_MAXD] = {"
                 % (sym, bg, bg))
    for r in range(rows):
        lines.append("    {" + ", ".join(str(v) for v in col[r]) + "},")
    lines.append("};")
    lines.append("")
    lines.append("static const %s %s_sh[BG%d_ROWS][BG%d_MAXD] = {"
                 % (ctype, sym, bg, bg))
    for r in range(rows):
        lines.append("    {" + ", ".join(str(v) for v in sh[r]) + "},")
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    text = "\n".join(lines) + "\n"
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s: BG%d i_LS=%d, %d rows x %d cols, Kb=%d, maxd=%d, shift type %s"
          % (out, bg, ils, rows, cols, kb, maxd, ctype))
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--bg", type=int, default=2, choices=(1, 2))
    ap.add_argument("--ils", type=int, default=None)
    ap.add_argument("--zc", type=int, default=None,
                    help="alternative to --ils: the lifting set that contains this Zc")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    ils = a.ils if a.ils is not None else (
        NR.zc_to_ils(a.zc) if a.zc else 0)
    raise SystemExit(emit(a.bg, ils, a.out))
