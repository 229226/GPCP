#!/usr/bin/env python3
"""Generate sw/soc/pusch_idft_tab.h: Q20 cosine table for the 360-point IDFT.

The DFT-s-OFDM PUSCH receiver deprecodes by an M-point IDFT
    T[m] = (1/M) * sum_k A[k] * exp(+2j*pi*m*k/M)
with M = E_BITS/2 = 360.  M is not a power of two, so the table is the
cheapest exact-enough route on a bare-metal RV64 core (no libm, no double:
-mabi=lp64d with -nostdlib would pull in libgcc soft-float helpers).

Q20 keeps the IDFT error around 0.1 LSB of the recovered QAM sample, far
below the QPSK decision distance, while the int64 accumulator still holds
360 * 2e6 * 2^20 = 7.5e14 (limit 9.2e18).
"""
import math

N = 360
SCALE = 1 << 20
vals = [int(round(math.cos(2.0 * math.pi * i / N) * SCALE)) for i in range(N)]

lines = [
    "/* Generated by tools/gen_pusch_idft_tab.py -- do not edit.",
    "   Q20 cosine table for the 360-point IDFT of the DFT-s-OFDM PUSCH",
    "   receiver.  sin(x) = cos(x - 90 deg), i.e. table index + N/4. */",
    "#ifndef PUSCH_IDFT_TAB_H",
    "#define PUSCH_IDFT_TAB_H",
    "",
    "#define IDFT_N       %d" % N,
    "#define IDFT_SCALE   %d" % SCALE,
    "",
    "static const int32_t idft_cos[IDFT_N] = {",
]
for i in range(0, N, 8):
    lines.append("    " + ", ".join("%8d" % v for v in vals[i:i + 8]) + ",")
lines += ["};", "", "#endif /* PUSCH_IDFT_TAB_H */", ""]

open("sw/soc/pusch_idft_tab.h", "w").write("\n".join(lines))
print("wrote sw/soc/pusch_idft_tab.h (%d entries, Q%d)" % (N, 20))
